#!/usr/bin/env node
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const OUT = path.join(ROOT, 'src', 'data', 'bankManifest.js');

const raw = execFileSync(
  process.execPath,
  [path.join(ROOT, 'scripts', 'validate-bank.mjs'), '--allow-incomplete', '--json'],
  { cwd: ROOT, encoding: 'utf8', maxBuffer: 20 * 1024 * 1024 }
);

const report = JSON.parse(raw);

if (report.qualityErrorCount > 0) {
  console.error('Refusing to sync bankManifest.js: quality errors detected!');
  console.error(report.qualityErrors.slice(0, 30).join('\n'));
  process.exit(1);
}

const stageTotals = { 'Class 11': 0, 'Class 12': 0, 'NEET practice': 0 };
const diffTotals = { easy: 0, medium: 0, hard: 0 };

const chapters = report.chapters.map((c) => {
  stageTotals['Class 11'] += c.stageCounts['Class 11'] || 0;
  stageTotals['Class 12'] += c.stageCounts['Class 12'] || 0;
  stageTotals['NEET practice'] += c.stageCounts['NEET practice'] || 0;
  diffTotals.easy += c.diffCounts.easy || 0;
  diffTotals.medium += c.diffCounts.medium || 0;
  diffTotals.hard += c.diffCounts.hard || 0;
  return {
    chapterId: c.chapterId,
    order: c.order,
    classStage: c.classStage,
    title: c.title,
    validCount: c.validCount,
    target: c.target,
    status: c.status === 'COMPLETE' ? 'complete' : 'in-progress',
    reviewComplete: c.reviewComplete,
    reviewSnapshotCurrent: c.reviewSnapshotCurrent,
    stageCounts: c.stageCounts,
    diffCounts: c.diffCounts,
    typeCounts: c.typeCounts,
    sectionCounts: c.sectionCounts,
  };
});

const manifest = {
  generatedAt: '2026-11-17',
  bankComplete: report.bankComplete,
  totalValid: report.totalValid,
  totalRequired: report.totalRequired,
  completeChapters: report.completeChapters,
  inProgressChapters: report.totalChapters - report.completeChapters,
  totalChapters: report.totalChapters,
  stageTotals,
  diffTotals,
  chapters,
};

const content = `// AUTO-GENERATED by scripts/sync-manifest.mjs from validated chapter packs.
// Never edit manually or mark an incomplete chapter as complete.
export const BANK_MANIFEST = ${JSON.stringify(manifest, null, 2)};

export const MANIFEST_BY_CHAPTER_ID = new Map(
  BANK_MANIFEST.chapters.map((ch) => [ch.chapterId, ch])
);
`;

fs.writeFileSync(OUT, content, 'utf8');
console.log(
  `Synced src/data/bankManifest.js: ${manifest.totalValid}/${manifest.totalRequired} automatically checked records (${manifest.completeChapters}/${manifest.totalChapters} chapters complete; bankComplete=${manifest.bankComplete}).`
);
