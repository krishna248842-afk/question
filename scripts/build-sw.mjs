#!/usr/bin/env node
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const DIST = path.join(ROOT, 'dist');

function walk(dir, base = '') {
  const results = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const rel = path.posix.join(base, entry.name);
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      results.push(...walk(full, rel));
    } else if (entry.name !== 'sw.js' && !entry.name.endsWith('.map')) {
      results.push(`/${rel}`);
    }
  }
  return results.sort();
}

const files = walk(DIST);
const hash = crypto.createHash('sha256');
for (const rel of files) {
  hash.update(rel);
  hash.update(fs.readFileSync(path.join(DIST, rel.slice(1))));
}
const version = hash.digest('hex').slice(0, 12);
const cacheName = `memoneet-offline-${version}`;
const precacheList = ['/', ...files];

const swSource = `// AUTO-GENERATED by scripts/build-sw.mjs — precaches app shell AND all lazy chapter packs for airplane-mode use.
const CACHE_NAME = ${JSON.stringify(cacheName)};
const PRECACHE_URLS = ${JSON.stringify(precacheList, null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => cache.addAll(PRECACHE_URLS))
  );
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(
        keys
          .filter((key) => key.startsWith('memoneet-') && key !== CACHE_NAME)
          .map((key) => caches.delete(key))
      )
    )
  );
  self.clients.claim();
});

self.addEventListener('fetch', (event) => {
  if (event.request.method !== 'GET') return;
  const url = new URL(event.request.url);
  if (url.origin !== self.location.origin) return;

  event.respondWith(
    caches.match(event.request).then((cached) => {
      if (cached) return cached;
      return fetch(event.request)
        .then((response) => {
          if (response && response.ok && response.type === 'basic') {
            const copy = response.clone();
            caches.open(CACHE_NAME).then((cache) => cache.put(event.request, copy));
          }
          return response;
        })
        .catch(() => {
          if (event.request.mode === 'navigate') {
            return caches.match('/index.html');
          }
          return new Response('Offline resource unavailable', { status: 503 });
        });
    })
  );
});
`;

fs.writeFileSync(path.join(DIST, 'sw.js'), swSource, 'utf8');
console.log(`Built dist/sw.js (${cacheName}) precaching ${precacheList.length} offline assets (including all chapter packs).`);
